// Stable Instagram thumbnail: redirects to a CDN-cached 640px image. Works in <img>.
export function igThumb(shortcode: string): string {
  return `https://www.instagram.com/p/${shortcode}/media/?size=m`;
}

// The real Instagram embed (genuine IG wrapper with likes + caption).
export function igEmbed(shortcode: string): string {
  return `https://www.instagram.com/p/${shortcode}/embed/captioned/`;
}

export function igPermalink(shortcode: string): string {
  return `https://www.instagram.com/p/${shortcode}/`;
}
