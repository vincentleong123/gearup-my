/**
 * Regenerates SEO_IMAGE_TODO.md - the full per-article in-article-image
 * checklist (every article visible in the /admin panel, admin order = date
 * desc) with batch progress filled in.
 *
 * Run: node scripts/gen-seo-image-todo.mjs
 */
import { readdirSync, readFileSync, existsSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import matter from 'gray-matter';
import { batch1 } from './seo-images-plan.mjs';

const ART_DIR = join(process.cwd(), 'content', 'articles');
const BLOG_DIR = join(process.cwd(), 'public', 'blog');
const OUT = join(process.cwd(), 'SEO_IMAGE_TODO.md');
const BASE = 'https://kameralog.com';

const planned = new Map(batch1.map((a) => [a.slug, a]));

const posts = readdirSync(ART_DIR)
  .filter((f) => f.endsWith('.md'))
  .map((f) => {
    const raw = readFileSync(join(ART_DIR, f), 'utf8');
    const { data, content } = matter(raw);
    return {
      file: f,
      slug: String(data.slug || f.replace(/\.md$/, '')),
      title: String(data.title || '').replace(/\s+/g, ' ').trim(),
      date: String(data.date || '').slice(0, 10),
      lang: data.lang === 'ms' ? 'ms' : 'en',
      content,
      hasInline: /^!\[[^\]]*\]\(\/blog\//m.test(content),
      qaPairs: Array.isArray(data.qaPairs) ? data.qaPairs.length : 0,
      hasSeoTitle: Boolean(data.seoTitle),
      hasSeoDesc: Boolean(data.seoDescription),
    };
  })
  .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

const batch1Slugs = new Set(batch1.map((a) => a.slug));
const url = (p) => `${BASE}${p.lang === 'ms' ? '/ms' : ''}/blog/${p.slug}`;

const rows = posts.map((p, i) => {
  const plan = planned.get(p.slug);
  let state = 'pending';
  let imgs = '-';
  if (plan) {
    const present = plan.images.filter(
      (im) => existsSync(join(BLOG_DIR, im.file)) && statSync(join(BLOG_DIR, im.file)).size > 15 * 1024,
    ).length;
    const inserted = plan.images.filter((im) => p.content.includes(im.file)).length;
    imgs = `${inserted}/2 inserted, ${present}/2 downloaded`;
    state = inserted === 2 ? 'DONE' : present === 2 ? 'ready to insert' : `fetching ${present}/2`;
  }
  return { i: i + 1, p, state, imgs, plan };
});

const doneCount = rows.filter((r) => r.state === 'DONE').length;
const batch1Rows = rows.filter((r) => batch1Slugs.has(r.p.slug));
const pendingRest = rows.filter((r) => !batch1Slugs.has(r.p.slug));

const out = [];
out.push('# SEO in-article image TODO - every article (admin order, date desc)');
out.push('');
out.push('Generated by `node scripts/gen-seo-image-todo.mjs`. Source of truth for the');
out.push('image plan itself: `scripts/seo-images-plan.mjs`.');
out.push('');
out.push('**Goal:** 2 extra in-article images per article (unique, on-site `/blog/*.jpg`,');
out.push('keyword-rich `alt` in the article language, visible `caption`, wired into the');
out.push('Article JSON-LD `image` array).');
out.push('');
out.push(`- Articles total: **${rows.length}**`);
out.push(`- Batch 1 (first 20, admin order): **${batch1Rows.length}** - ${doneCount}/20 fully done`);
out.push(`- Remaining batches: **${pendingRest.length}**`);
out.push('');
out.push('## How each row is checked');
out.push('');
out.push('1. Open the URL, view source: the two `/blog/<file>.jpg` `<img>` tags must be');
out.push('   present with their `alt` and `<figcaption>`.');
out.push('2. `application/ld+json` Article block must list 3 images (cover + 2 inline).');
out.push('3. Image files must be 1600x900 and look right for the section they sit in.');
out.push('');
out.push('## Batch 1 - first 20 articles');
out.push('');
out.push('| # | State | Date | Lang | Article | Images | URL |');
out.push('|---|---|---|---|---|---|---|');
for (const r of batch1Rows) {
  out.push(
    `| ${r.i} | ${r.state} | ${r.p.date} | ${r.p.lang} | ${r.p.title.slice(0, 70)} | ${r.imgs} | ${url(r.p)} |`,
  );
}
out.push('');
out.push('### Batch 1 image detail (alt text to eyeball on the live page)');
out.push('');
for (const r of batch1Rows) {
  out.push(`**${r.i}. ${r.p.slug}** - ${url(r.p)}`);
  if (r.plan) {
    for (const im of r.plan.images) {
      out.push(`- \`${im.file}\` (after H2 #${im.afterH2})`);
      out.push(`  - alt: ${im.alt}`);
      out.push(`  - caption: ${im.caption}`);
    }
  }
  out.push('');
}
out.push('## Remaining articles - batches 2+');
out.push('');
out.push('| # | Date | Lang | Article | State | URL |');
out.push('|---|---|---|---|---|---|');
for (const r of pendingRest) {
  out.push(`| ${r.i} | ${r.p.date} | ${r.p.lang} | ${r.p.title.slice(0, 70)} | pending | ${url(r.p)} |`);
}
out.push('');

writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`wrote ${OUT}: ${rows.length} articles, batch1=${batch1Rows.length}, done=${doneCount}`);
